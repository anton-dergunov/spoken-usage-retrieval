def token_records(text: str, values: list[str], prefix: str) -> list[dict[str, object]]:
    cursor = 0
    records: list[dict[str, object]] = []
    for index, value in enumerate(values, 1):
        start = text.find(value, cursor)
        if start < 0:
            raise ValueError(f"cannot locate {value!r} after {cursor} in {text!r}")
        end = start + len(value)
        records.append(
            {"id": f"{prefix}{index}", "text": value, "range": {"start": start, "end": end}}
        )
        cursor = end
    return records


def build() -> list[dict[str, object]]:
    result: list[dict[str, object]] = []
    for (
        case_id,
        split,
        language,
        source,
        target,
        source_values,
        target_values,
        links,
        phenomena,
        note,
    ) in CASES:
        source_tokens = token_records(source, source_values, "S")
        target_tokens = token_records(target, target_values, "T")
        sure = [
            [f"S{int(left)}", f"T{int(right)}"]
            for left, right in (item.split("-") for item in links.split())
        ]
        linked_source = {edge[0] for edge in sure}
        linked_target = {edge[1] for edge in sure}
        record: dict[str, object] = {
            "id": case_id,
            "split": split,
            "source_language": language,
            "target_language": "en",
            "source_text": source,
            "target_text": target,
            "source_tokens": source_tokens,
            "target_tokens": target_tokens,
            "sure_links": sure,
            "possible_links": [],
            "unaligned_source_ids": [
                token["id"] for token in source_tokens if token["id"] not in linked_source
            ],
            "unaligned_target_ids": [
                token["id"] for token in target_tokens if token["id"] not in linked_target
            ],
            "phenomena": phenomena,
            "provenance": "project-created challenge sentence and annotation",
            "annotation_notes": note,
        }
        result.append(record)
    return result


